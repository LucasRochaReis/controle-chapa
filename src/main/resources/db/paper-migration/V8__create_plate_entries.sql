create table if not exists plate_production_entries (
    id bigint generated by default as identity primary key,
    entry_date date not null,
    op_code varchar(60) not null,
    client_name varchar(150) not null,
    quantity integer not null,
    machine_id bigint,
    operator_name varchar(100) not null,
    shift_id bigint not null,
    plate varchar(80) not null,
    ctp varchar(80) not null,
    observations varchar(500),
    created_at timestamp not null,
    created_by varchar(50) not null,
    constraint fk_plate_production_shift foreign key (shift_id) references lookup_options(id),
    constraint fk_plate_production_machine foreign key (machine_id) references lookup_options(id)
);

create index if not exists idx_plate_production_date on plate_production_entries(entry_date);
create index if not exists idx_plate_production_op on plate_production_entries(op_code);
create index if not exists idx_plate_production_machine on plate_production_entries(machine_id);
create index if not exists idx_plate_production_shift on plate_production_entries(shift_id);
create index if not exists idx_plate_production_client on plate_production_entries(client_name);

create table if not exists plate_defect_entries (
    id bigint generated by default as identity primary key,
    entry_date date not null,
    op_code varchar(60) not null,
    client_name varchar(150) not null,
    loss_quantity integer not null,
    defect_code varchar(60) not null,
    machine_id bigint,
    operator_name varchar(100) not null,
    shift_id bigint not null,
    plate varchar(80) not null,
    ctp varchar(80) not null,
    sector varchar(80) not null,
    observations varchar(500),
    created_at timestamp not null,
    created_by varchar(50) not null,
    constraint fk_plate_defect_shift foreign key (shift_id) references lookup_options(id),
    constraint fk_plate_defect_machine foreign key (machine_id) references lookup_options(id)
);

create index if not exists idx_plate_defect_date on plate_defect_entries(entry_date);
create index if not exists idx_plate_defect_op on plate_defect_entries(op_code);
create index if not exists idx_plate_defect_machine on plate_defect_entries(machine_id);
create index if not exists idx_plate_defect_shift on plate_defect_entries(shift_id);
create index if not exists idx_plate_defect_client on plate_defect_entries(client_name);
create index if not exists idx_plate_defect_sector on plate_defect_entries(sector);
