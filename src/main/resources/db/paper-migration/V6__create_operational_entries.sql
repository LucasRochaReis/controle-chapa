create table if not exists operational_entries (
    id bigint generated by default as identity primary key,
    type varchar(30) not null,
    entry_date date not null,
    shift_id bigint not null,
    machine_id bigint not null,
    cut_responsible varchar(100) not null,
    observations varchar(500),
    created_at timestamp not null,
    created_by varchar(50) not null,
    constraint fk_operational_entries_shift foreign key (shift_id) references lookup_options(id),
    constraint fk_operational_entries_machine foreign key (machine_id) references lookup_options(id)
);

create index if not exists idx_operational_entries_type on operational_entries(type);
create index if not exists idx_operational_entries_date on operational_entries(entry_date);
create index if not exists idx_operational_entries_machine on operational_entries(machine_id);
