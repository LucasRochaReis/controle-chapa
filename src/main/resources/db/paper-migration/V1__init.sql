create table if not exists app_users (
    id bigint generated by default as identity primary key,
    username varchar(50) not null,
    password varchar(120) not null,
    name varchar(100) not null,
    enabled boolean not null default true,
    constraint uk_app_users_username unique (username)
);

create table if not exists lookup_options (
    id bigint generated by default as identity primary key,
    category varchar(30) not null,
    label varchar(80) not null,
    active boolean not null default true,
    sort_order integer not null default 0,
    constraint uk_lookup_category_label unique (category, label)
);

create table if not exists paper_entries (
    id bigint generated by default as identity primary key,
    entry_date date not null,
    shift_id bigint not null,
    op_code varchar(60) not null,
    paper_type varchar(120) not null,
    paper_format varchar(120) not null,
    paper_grammage varchar(60) not null,
    quantity_released integer not null,
    quantity_received integer not null,
    cut_responsible varchar(100) not null,
    print_responsible varchar(100) not null,
    observations varchar(500),
    created_at timestamp not null,
    created_by varchar(50) not null,
    constraint fk_paper_entries_shift foreign key (shift_id) references lookup_options(id)
);

create index if not exists idx_lookup_category on lookup_options(category);
create index if not exists idx_paper_entries_date on paper_entries(entry_date);
create index if not exists idx_paper_entries_shift on paper_entries(shift_id);
create index if not exists idx_paper_entries_op on paper_entries(op_code);
